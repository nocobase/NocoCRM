// Russian counts in four plural forms (one, few, many, other), while the
// copy has `_one` and `_other` alone; i18next shows English for a form it
// does not find (2 and 5 among them). Every `_other` is worded to fit any
// number ("Сделок: {{count}}"), so it stands for `_few` and `_many` too.
function withRussianPlurals<T>(resource: T): T {
  if (!resource || typeof resource !== 'object') return resource;
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(resource)) {
    out[key] = withRussianPlurals(value);
    if (key.endsWith('_other') && typeof value === 'string') {
      const stem = key.slice(0, -'_other'.length);
      out[`${stem}_few`] ??= value;
      out[`${stem}_many`] ??= value;
    }
  }
  return out as T;
}

export default withRussianPlurals(ruRU);
